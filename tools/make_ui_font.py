"""Generate the small Chinese UI glyph subset using Windows' installed font.

No downloaded font or Python package is required. The generated header is
committed with the source, so firmware builds do not need Windows/GDI.
"""
from __future__ import annotations

import ctypes
import re
from ctypes import wintypes
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GLYPH_SIZE = 10
CANVAS_SIZE = 32
LABELS = """
功能菜单复制粘贴番茄时钟硬件监控电脑音量上下选择中键进入左返回
开始暂停继续重置专注休息分钟轮次完成等待连接离线已发送失败权限受限
认证错误正在排队队列忙过期取消未配置网络静音取消静音调整切页校时
年月日一二三四五六周负载内存显卡温度磁盘使用率设备不可用实时
↑↓←→
"""


class BITMAPINFOHEADER(ctypes.Structure):
    _fields_ = [("size", wintypes.DWORD), ("width", wintypes.LONG),
                ("height", wintypes.LONG), ("planes", wintypes.WORD),
                ("bit_count", wintypes.WORD), ("compression", wintypes.DWORD),
                ("image_size", wintypes.DWORD), ("x_ppm", wintypes.LONG),
                ("y_ppm", wintypes.LONG), ("colors_used", wintypes.DWORD),
                ("colors_important", wintypes.DWORD)]


def main():
    gdi = ctypes.WinDLL("gdi32", use_last_error=True)
    gdi.CreateCompatibleDC.argtypes = [wintypes.HDC]
    gdi.CreateCompatibleDC.restype = wintypes.HDC
    gdi.CreateDIBSection.argtypes = [wintypes.HDC, ctypes.POINTER(BITMAPINFOHEADER),
                                   wintypes.UINT, ctypes.POINTER(ctypes.c_void_p),
                                   wintypes.HANDLE, wintypes.DWORD]
    gdi.CreateDIBSection.restype = wintypes.HBITMAP
    gdi.SelectObject.argtypes = [wintypes.HDC, wintypes.HANDLE]
    gdi.SelectObject.restype = wintypes.HANDLE
    gdi.CreateFontW.argtypes = [ctypes.c_int] * 5 + [wintypes.DWORD] * 8 + [wintypes.LPCWSTR]
    gdi.CreateFontW.restype = wintypes.HFONT
    gdi.SetTextColor.argtypes = [wintypes.HDC, wintypes.DWORD]
    gdi.SetBkColor.argtypes = [wintypes.HDC, wintypes.DWORD]
    gdi.TextOutW.argtypes = [wintypes.HDC, ctypes.c_int, ctypes.c_int, wintypes.LPCWSTR, ctypes.c_int]
    gdi.DeleteObject.argtypes = [wintypes.HANDLE]
    gdi.DeleteDC.argtypes = [wintypes.HDC]
    dc = gdi.CreateCompatibleDC(None)
    byte_count = CANVAS_SIZE * CANVAS_SIZE * 4
    info = BITMAPINFOHEADER(40, CANVAS_SIZE, -CANVAS_SIZE, 1, 32, 0, byte_count, 0, 0, 0, 0)
    pixels = ctypes.c_void_p()
    bitmap = gdi.CreateDIBSection(dc, ctypes.byref(info), 0, ctypes.byref(pixels), None, 0)
    if not dc or not bitmap:
        raise ctypes.WinError(ctypes.get_last_error())
    old_bitmap = gdi.SelectObject(dc, bitmap)
    font = gdi.CreateFontW(-10, 0, 0, 0, 500, 0, 0, 0, 134, 0, 0, 4, 0, "Microsoft YaHei")
    if not font:
        raise ctypes.WinError(ctypes.get_last_error())
    old_font = gdi.SelectObject(dc, font)
    gdi.SetTextColor(dc, 0xFFFFFF)
    gdi.SetBkColor(dc, 0)
    lines = ["#pragma once", "#include <stdint.h>", "#include <pgmspace.h>",
             "// Generated by tools/make_ui_font.py: complete 10x10 UI glyphs.",
             f"constexpr int uiGlyphWidth = {GLYPH_SIZE}, uiGlyphHeight = {GLYPH_SIZE};",
             f"struct UiGlyph {{ uint32_t codepoint; uint8_t rows[{GLYPH_SIZE * 2}]; }};",
             "static const UiGlyph uiGlyphs[] PROGMEM = {"]
    strings = LABELS
    for directory in (ROOT / "include", ROOT / "src"):
        for path in directory.iterdir():
            if path.suffix in (".h", ".cpp") and path.name != "ui_font.h":
                strings += "".join(re.findall(r'"([^"\n]*)"', path.read_text(encoding="utf-8")))
    try:
        for char in sorted({c for c in strings if ord(c) > 127}):
            ctypes.memset(pixels, 0, byte_count)
            # Generous padding captures all bearings and descenders before packing.
            if not gdi.TextOutW(dc, 6, 6, char, 1):
                raise ctypes.WinError(ctypes.get_last_error())
            gdi.GdiFlush()
            raw = ctypes.string_at(pixels, byte_count)
            ink = []
            for y in range(CANVAS_SIZE):
                for x in range(CANVAS_SIZE):
                    offset = (y * CANVAS_SIZE + x) * 4
                    if max(raw[offset:offset + 3]) >= 100:
                        ink.append((x, y))
            if not ink:
                raise ValueError(f"No glyph rendered for {char!r}")
            left, right = min(x for x, _ in ink), max(x for x, _ in ink)
            top, bottom = min(y for _, y in ink), max(y for _, y in ink)
            if min(left, top) == 0 or max(right, bottom) == CANVAS_SIZE - 1:
                raise ValueError(f"Glyph touches render boundary: {char!r}")
            width, height = right - left + 1, bottom - top + 1
            # Keep every ink pixel. Rare oversized glyphs fit proportionally;
            # the regular CJK glyphs at this font size need no resampling.
            ratio = min(1.0, GLYPH_SIZE / max(width, height))
            target_width, target_height = max(1, round(width * ratio)), max(1, round(height * ratio))
            x_pad, y_pad = (GLYPH_SIZE - target_width) // 2, (GLYPH_SIZE - target_height) // 2
            mask = set()
            for x, y in ink:
                dx = min(target_width - 1, int((x - left) * target_width / width))
                dy = min(target_height - 1, int((y - top) * target_height / height))
                mask.add((x_pad + dx, y_pad + dy))
            packed = []
            for y in range(GLYPH_SIZE):
                bits = 0
                for x in range(GLYPH_SIZE):
                    if (x, y) in mask:
                        bits |= 1 << (15 - x)
                packed.extend((bits >> 8, bits & 255))
            data = ",".join(f"0x{x:02x}" for x in packed)
            lines.append(f"  {{0x{ord(char):x}, {{{data}}}}}, // {char}")
    finally:
        gdi.SelectObject(dc, old_font)
        gdi.SelectObject(dc, old_bitmap)
        gdi.DeleteObject(font)
        gdi.DeleteObject(bitmap)
        gdi.DeleteDC(dc)
    lines.extend(["};", "constexpr unsigned uiGlyphCount = sizeof(uiGlyphs) / sizeof(uiGlyphs[0]);", ""])
    destination = ROOT / "include" / "ui_font.h"
    destination.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {len(set(c for c in strings if ord(c) > 127))} complete {GLYPH_SIZE}x{GLYPH_SIZE} glyphs: {destination.name}")


if __name__ == "__main__":
    main()
