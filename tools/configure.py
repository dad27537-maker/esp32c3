"""Create matching board/PC configuration without third-party Python packages."""
from __future__ import annotations

import argparse
import getpass
import ipaddress
import json
from pathlib import Path
import secrets
import socket

ROOT = Path(__file__).resolve().parents[1]


def cpp_string(value: str) -> str:
    # Emit UTF-8 as fixed-width octal escapes; works with Chinese SSIDs too.
    return '"' + "".join(f"\\{byte:03o}" for byte in value.encode("utf-8")) + '"'


def suggested_ip() -> str:
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
            # Choosing a route sends no UDP payload and needs no Internet server.
            sock.connect(("192.0.2.1", 9))
            return sock.getsockname()[0]
    except OSError:
        return ""


def write_configuration(root: Path, ssid: str, password: str, host: str, port: int) -> None:
    ipaddress.IPv4Address(host)
    if not 1 <= port <= 65535:
        raise ValueError("Port must be between 1 and 65535")
    if not 1 <= len(ssid.encode("utf-8")) <= 32:
        raise ValueError("WiFi SSID must be between 1 and 32 UTF-8 bytes")
    token = secrets.token_hex(24)
    header = "#pragma once\n// Generated by tools/configure.py; do not publish.\n"
    for key, value in (("WIFI_SSID", ssid), ("WIFI_PASSWORD", password),
                       ("PC_HOST", host), ("API_TOKEN", token)):
        header += f"#define {key} {cpp_string(value)}\n"
    header += f"#define PC_PORT {port}\n"
    (root / "include").mkdir(parents=True, exist_ok=True)
    (root / "pc").mkdir(parents=True, exist_ok=True)
    (root / "include" / "secrets.h").write_text(header, encoding="utf-8")
    (root / "pc" / "receiver_config.json").write_text(
        json.dumps({"port": port, "token": token}, indent=2) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=8765)
    args = parser.parse_args()
    print("WiFi 快捷键板配置（电脑和板子需要在同一局域网）")
    if (ROOT / "include" / "secrets.h").exists():
        if input("已有配置，将更新两端令牌并需要重新烧录。继续？[y/N] ").lower() != "y":
            return
    ssid = input("2.4GHz WiFi 名称：")
    password = getpass.getpass("WiFi 密码（输入时不显示；开放网络直接回车）：")
    candidate = suggested_ip()
    print("请用 ipconfig 核对与板子相同网络的 IPv4；VPN/虚拟网卡可能影响默认值。")
    host = input(f"本电脑局域网 IPv4 [{candidate}]：").strip() or candidate
    try:
        write_configuration(ROOT, ssid, password, host, args.port)
    except ValueError as exc:
        parser.error(str(exc))
    print("已生成 include/secrets.h 和 pc/receiver_config.json（未显示密码/令牌）。")
    print("下一步：编译并烧录固件，然后运行 python pc/receiver.py。")


if __name__ == "__main__":
    main()
